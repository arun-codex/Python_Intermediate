# CHALLENGE 3 — REVERSE NUMBER

def reverse_number(number):
    reverse = 0
    while number > 0:
        reverse = (reverse*10)+number%10
        number = number // 10
    print(f"Reverse: {reverse}")

reverse_number(12345)